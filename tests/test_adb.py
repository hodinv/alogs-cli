def test_local_properties_windows_escaping(tmp_path):
    from alogs.sources.adb_source import sdk_dir_from_local_properties

    (tmp_path / "local.properties").write_text(
        "## This file is automatically generated by Android Studio.\n"
        "# Do not modify this file -- YOUR CHANGES WILL BE ERASED!\n"
        r"sdk.dir=C\:\\Users\\me\\AppData\\Local\\Android\\Sdk" "\n",
        encoding="utf-8",
    )
    assert sdk_dir_from_local_properties(tmp_path) == Path(r"C:\Users\me\AppData\Local\Android\Sdk")


def test_local_properties_forms_and_parent_lookup(tmp_path):
    from alogs.sources.adb_source import sdk_dir_from_local_properties

    project = tmp_path / "project"
    sub = project / "app" / "src"
    sub.mkdir(parents=True)
    (project / "local.properties").write_text("! comment\n" r"sdk.dir : /opt/android\u002dsdk" "\n", encoding="utf-8")
    assert sdk_dir_from_local_properties(sub) == Path("/opt/android-sdk")
    # the nearest local.properties decides, even if it has no sdk.dir
    (sub / "local.properties").write_text("ndk.dir=/x\n", encoding="utf-8")
    assert sdk_dir_from_local_properties(sub) is None


def test_find_adb_order(tmp_path, monkeypatch):
    monkeypatch.delenv("ALOGS_ADB", raising=False)
    exe = "adb.exe" if sys.platform == "win32" else "adb"

    def sdk(name):
        tools = tmp_path / name / "platform-tools"
        tools.mkdir(parents=True)
        (tools / exe).write_text("")
        return tmp_path / name, str(tools / exe)

    props_sdk, props_adb = sdk("props-sdk")
    home_sdk, home_adb = sdk("home-sdk")
    project = tmp_path / "project"
    project.mkdir()
    escaped = str(props_sdk).replace("\\", "\\\\").replace(":", "\\:")  # as Android Studio writes it
    (project / "local.properties").write_text(f"sdk.dir={escaped}\n", encoding="utf-8")
    monkeypatch.chdir(project)
    monkeypatch.setenv("ANDROID_HOME", str(home_sdk))

    monkeypatch.setattr(adb_source.shutil, "which", lambda name: "/on/path/adb")
    assert find_adb() == ["/on/path/adb"]  # 1. PATH
    monkeypatch.setattr(adb_source.shutil, "which", lambda name: None)
    assert find_adb() == [props_adb]  # 2. local.properties
    (project / "local.properties").unlink()
    assert find_adb() == [home_adb]  # 3. ANDROID_HOME
