FAKE_ADB = Path(__file__).parent / "fake_adb.py"
LINES = [
    "01-02 03:04:05.678  1234  5678 D MyTag   : hello",
    "01-02 03:04:05.679  1234  5678 I MyTag   : world",
]


@pytest.fixture
def fake_adb(tmp_path, monkeypatch):
    log = tmp_path / "device.log"
    log.write_text("\n".join(LINES) + "\n", encoding="utf-8")
    calls = tmp_path / "calls.txt"
    monkeypatch.setenv("ALOGS_ADB", f'"{sys.executable}" "{FAKE_ADB}"')
    monkeypatch.setenv("FAKE_ADB_LOG", str(log))
    monkeypatch.setenv("FAKE_ADB_CALLS", str(calls))
    for var in ("FAKE_ADB_HANG", "FAKE_ADB_NO_MODIFIERS", "FAKE_ADB_DELAY", "FAKE_ADB_EXIT", "FAKE_ADB_DEVICES"):
        monkeypatch.delenv(var, raising=False)
    return calls


def test_find_adb_env_override(monkeypatch):
    monkeypatch.setenv("ALOGS_ADB", r'"C:\Program Files\py.exe" "C:\x\fake adb.py"')
    assert find_adb() == [r"C:\Program Files\py.exe", r"C:\x\fake adb.py"]


def test_find_adb_sdk_fallback(tmp_path, monkeypatch):
    monkeypatch.delenv("ALOGS_ADB", raising=False)
    monkeypatch.chdir(tmp_path)  # no local.properties around
    monkeypatch.setattr(adb_source.shutil, "which", lambda name: None)
    exe = "adb.exe" if sys.platform == "win32" else "adb"
    tools = tmp_path / "sdk" / "platform-tools"
    tools.mkdir(parents=True)
    (tools / exe).write_text("")
    monkeypatch.setenv("ANDROID_HOME", str(tmp_path / "sdk"))
    assert find_adb() == [str(tools / exe)]
    monkeypatch.delenv("ANDROID_HOME")
    monkeypatch.setattr(adb_source, "_sdk_dirs", lambda: [])
    assert find_adb() is None


def test_list_devices(fake_adb, monkeypatch):
    monkeypatch.setenv("FAKE_ADB_DEVICES", "emulator-5554:device,R58M:unauthorized")
    assert list_devices(find_adb()) == [Device("emulator-5554", "device"), Device("R58M", "unauthorized")]


def test_choose_device():
    ok, bad, off = Device("a", "device"), Device("b", "unauthorized"), Device("c", "offline")
    assert choose_device([ok], None) is ok
    assert choose_device([ok, bad], "a") is ok
    with pytest.raises(AdbError, match="no devices"):
        choose_device([], None)
    with pytest.raises(AdbError, match="more than one device: a, b"):
        choose_device([ok, bad], None)
    with pytest.raises(AdbError, match="unauthorized"):
        choose_device([bad], None)
    with pytest.raises(AdbError, match="offline"):
        choose_device([off], None)
    with pytest.raises(AdbError, match="'zzz' not found"):
        choose_device([ok], "zzz")


def test_stream_uses_preferred_format(fake_adb):
    src = AdbSource(find_adb(), "emulator-5554")
    lines = [line for line in src.iter_lines() if line is not None]
    assert lines == LINES
    assert src.returncode == 0
    assert "device went away" in src.error
    assert fake_adb.read_text().splitlines() == [
        "-s emulator-5554 logcat -v threadtime -v year -v usec",
    ]


def test_stream_falls_back_to_plain_threadtime(fake_adb, monkeypatch):
    monkeypatch.setenv("FAKE_ADB_NO_MODIFIERS", "1")
    src = AdbSource(find_adb(), "emulator-5554")
